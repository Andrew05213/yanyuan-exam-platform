import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=n=>JSON.parse(fs.readFileSync(new URL('../public/'+n,import.meta.url)));
const data=read('exam-standards.json'),catalog=read('difficulty.json');
const box={};vm.createContext(box);vm.runInContext(fs.readFileSync(new URL('../public/exam-standards.js',import.meta.url),'utf8'),box);
const E=box.ExamStandardEngine;E.validate(data);
const s=data.schools.thu;
assert.deepEqual(Object.values(s.subjects).map(x=>x.totalQuestions),[50,40,30]);
const cn=s.subjects['语文'],en=s.subjects['英语'],math=s.subjects['数学'];
assert.equal(cn.sections.find(x=>x.id==='classical-argument').count,5);
assert.equal(cn.sections.find(x=>x.id==='classical-biography').count,6);
assert.deepEqual(cn.sections.find(x=>x.id==='vernacular-fiction').composition,[{kind:'mc',count:4},{kind:'multiple',count:1}]);
assert.equal(cn.sections.find(x=>x.id==='modern-poetry').passageType,'现代诗歌');
assert(en.sections.every(x=>x.optionCount===4));
assert.equal(en.sections.find(x=>x.id==='reading').passageCount,4);
assert.equal(en.sections.find(x=>x.id==='cloze').blanks,10);
assert.deepEqual(math.sections.map(x=>[x.count,x.questionKind,x.optionCount]),[[10,'mc',4],[20,'indefinite',4]]);
assert(Object.values(s.subjects).every(x=>x.minutes===null&&x.totalPoints===null));
assert(Object.entries(s.subjects).every(([subject,v])=>v.sections.every(sec=>catalog.items.every(u=>!E.eligible(u,'thu',subject,sec)))),'legacy stock must not be counted as calibrated exam material');
const cloze=en.sections.find(x=>x.id==='cloze');
const unit={subject:'英语',passageType:'完形填空',examCalibration:{schoolId:'thu',sectionId:'cloze',reviewed:true},questions:Array.from({length:10},()=>({kind:'mc',options:['A','B','C','D']}))};
assert(E.eligible(unit,'thu','英语',cloze));
assert(!E.eligible({...unit,questions:[...unit.questions,...unit.questions.slice(0,5)]},'thu','英语',cloze),'15-blank unit must not replace a 10-blank unit');
assert(!E.eligible({...unit,questions:unit.questions.map(q=>({...q,options:['A','B','C']}))},'thu','英语',cloze));
const indefinite=math.sections[1];
const mathUnit={subject:'数学',examCalibration:{schoolId:'thu',sectionId:indefinite.id,reviewed:true},questions:[{kind:'mc',options:['A','B','C','D']}]};
assert(!E.eligible(mathUnit,'thu','数学',indefinite),'single-choice cannot replace indefinite-choice');
assert(E.eligible({...mathUnit,questions:[{kind:'indefinite',options:['A','B','C','D']}]},'thu','数学',indefinite));
const mutated=structuredClone(data);mutated.schools.thu.subjects['语文'].sections.at(-1).count=6;assert.throws(()=>E.validate(mutated));
const html=fs.readFileSync(new URL('../public/training.html',import.meta.url),'utf8');
assert(html.includes('exam-standards.js'));
const app=fs.readFileSync(new URL('../public/app.js',import.meta.url),'utf8');assert(app.includes('exam-standards.json'));assert(app.includes('ExamStandards.init(standards)'));
console.log('PASS: THU 50/40/30 structure, corrected history argument, unknown metadata, four-option constraints, strict ten-blank cloze and distinct multiple/indefinite formats; generic stock excluded.');

